static const uint16_t SOLUNE_NOTE_COUNT =
  sizeof(soluneTheme) / sizeof(soluneTheme[0]);

static uint16_t soluneIndex = 0;
static unsigned long soluneStarted = 0;
static bool solunePlaying = false;
static bool soluneNoteStarted = false;

void startSolune(){
  soluneIndex = 0;
  soluneStarted = millis();
  solunePlaying = true;
  soluneNoteStarted = false;

  buzzerOff();
  clearEncoderEvents();
  state = STATE_SOLUNE;
  invalidateLCD();
  lcd.clear();
}

void updateSoluneApp(){
  drawLCD("SOLUNE","MAIN THEME");
  showEclipseLogo();
  rgbPurple();

  if(!solunePlaying)return;

  unsigned long elapsed = millis() - soluneStarted;

  if(soluneIndex >= SOLUNE_NOTE_COUNT){
    buzzerOff();
    soluneStarted = millis();
    soluneIndex = 0;
    soluneNoteStarted = false;
    return;
  }

  const SoluneNote &note = soluneTheme[soluneIndex];

  if(!soluneNoteStarted && elapsed >= note.startMs){
    playTone(note.frequency, note.duration);
    soluneNoteStarted = true;
    soluneIndex++;
  }

  if(soluneIndex < SOLUNE_NOTE_COUNT &&
     elapsed >= soluneTheme[soluneIndex].startMs){
    soluneNoteStarted = false;
  }

  if(consumeEncoderPress()){
    buzzerOff();
    solunePlaying = false;
    returnToSongsMenu();
  }
}
